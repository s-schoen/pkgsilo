// The types whose resources an identity owns: their actions are listed with the permissions
// endpoint's owner parameter, the creates of API keys and every action on a password.
export function isOwnedAction(action: string): boolean {
  return action.startsWith("apikey:create:") || action.startsWith("password:");
}
